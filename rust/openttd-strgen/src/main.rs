//! `openttd-strgen STRINGS_H TABLE_STRINGS_RS...`: fails unless each `table::strings` source a
//! Rust archive compiled, which `openttd-kernels`' build script writes from the master language
//! file and copies for this check, holds the `StringID` constants of the `table/strings.h` C++
//! strgen wrote from the same file, name for name and value for value. Each `CMake` build runs it
//! on both archives' copies before linking the game and its native tests.

use std::collections::BTreeMap;
use std::process::ExitCode;
use std::{env, fs};

use openttd_strgen::table_strings;

/// The `static const StringID NAME = 0xID;` lines of `HeaderFileWriter::WriteStringID`, in file
/// order.
fn header_string_ids(header: &str) -> Result<Vec<(String, u32)>, String> {
    let mut ids = Vec::new();
    for line in header.lines() {
        let Some(definition) = line.strip_prefix("static const StringID ") else {
            continue;
        };
        let parsed = definition
            .strip_suffix(';')
            .and_then(|definition| definition.split_once(" = 0x"))
            .and_then(|(name, id)| Some((name.to_owned(), u32::from_str_radix(id, 16).ok()?)));
        ids.push(parsed.ok_or_else(|| format!("unreadable string ID line: {line}"))?);
    }
    Ok(ids)
}

/// One line per name whose ID differs or that only one list has; empty when both lists are equal.
fn differences(derived: &[(String, u32)], header: &[(String, u32)]) -> Vec<String> {
    if derived == header {
        return Vec::new();
    }
    let derived_ids: BTreeMap<_, _> = derived.iter().map(|(name, id)| (name, *id)).collect();
    let header_ids: BTreeMap<_, _> = header.iter().map(|(name, id)| (name, *id)).collect();
    let mut lines = Vec::new();
    for (name, id) in &derived_ids {
        match header_ids.get(name) {
            None => lines.push(format!("{name}: 0x{id:X} in Rust, absent from strings.h")),
            Some(header_id) if header_id != id => lines.push(format!(
                "{name}: 0x{id:X} in Rust, 0x{header_id:X} in strings.h"
            )),
            Some(_) => {}
        }
    }
    for (name, id) in &header_ids {
        if !derived_ids.contains_key(name) {
            lines.push(format!("{name}: absent from Rust, 0x{id:X} in strings.h"));
        }
    }
    if lines.is_empty() {
        lines.push("the same names and IDs, in a different order or repeated".to_owned());
    }
    lines
}

fn check(strings_h: &str, tables: &[String]) -> Result<(), String> {
    let read = |path: &str| fs::read(path).map_err(|error| format!("{path}: {error}"));
    let header = header_string_ids(&String::from_utf8_lossy(&read(strings_h)?))
        .map_err(|error| format!("{strings_h}: {error}"))?;
    let mut failures = Vec::new();
    for table in tables {
        let compiled = table_strings::read(&String::from_utf8_lossy(&read(table)?))
            .map_err(|error| format!("{table}: {error}"))?;
        let lines = differences(&compiled, &header);
        if !lines.is_empty() {
            failures.push(format!(
                "table::strings compiled from {table} differs from {strings_h}:\n{}",
                lines.join("\n")
            ));
        }
    }
    if failures.is_empty() {
        Ok(())
    } else {
        Err(failures.join("\n"))
    }
}

fn main() -> ExitCode {
    let arguments: Vec<String> = env::args().skip(1).collect();
    let Some((strings_h, tables)) = arguments
        .split_first()
        .filter(|(_, tables)| !tables.is_empty())
    else {
        eprintln!("usage: openttd-strgen STRINGS_H TABLE_STRINGS_RS...");
        return ExitCode::FAILURE;
    };
    match check(strings_h, tables) {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("{message}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const MASTER: &str = "##id 0x0\nSTR_A :a\nSTR_B :b\n##id 0x10\nSTR_C :c\n";

    fn header(lines: &[&str]) -> String {
        format!(
            "/* This file is automatically generated. Do not modify */\n\n\
             #ifndef TABLE_STRINGS_H\n#define TABLE_STRINGS_H\n{}\n\
             static const uint LANGUAGE_TOTAL_STRINGS    = 4;\n\n\
             #endif /* TABLE_STRINGS_H */\n",
            lines.join("\n")
        )
    }

    fn compare(lines: &[&str]) -> Vec<String> {
        let ids = openttd_strgen::strgen_base::master_string_ids(MASTER.as_bytes()).unwrap();
        let derived = table_strings::read(&table_strings::write(&ids)).unwrap();
        differences(&derived, &header_string_ids(&header(lines)).unwrap())
    }

    /// The header `HeaderFileWriter` writes for `MASTER`, with its blank line before a jump.
    #[test]
    fn matching_header_passes() {
        assert_eq!(
            compare(&[
                "static const StringID STR_A = 0x0;",
                "static const StringID STR_B = 0x1;",
                "",
                "static const StringID STR_C = 0x10;",
                "static const StringID STR_LAST_STRINGID = 0x10;",
            ]),
            Vec::<String>::new()
        );
    }

    /// A changed value, a missing name and an added name are each reported.
    #[test]
    fn differing_header_fails() {
        assert_eq!(
            compare(&[
                "static const StringID STR_A = 0x0;",
                "static const StringID STR_B = 0x2;",
                "static const StringID STR_D = 0x11;",
                "static const StringID STR_LAST_STRINGID = 0x10;",
            ]),
            [
                "STR_B: 0x1 in Rust, 0x2 in strings.h",
                "STR_C: 0x10 in Rust, absent from strings.h",
                "STR_D: absent from Rust, 0x11 in strings.h",
            ]
        );
    }

    /// Equal names and IDs in another order still fail.
    #[test]
    fn reordered_header_fails() {
        assert_eq!(
            compare(&[
                "static const StringID STR_B = 0x1;",
                "static const StringID STR_A = 0x0;",
                "static const StringID STR_C = 0x10;",
                "static const StringID STR_LAST_STRINGID = 0x10;",
            ]),
            ["the same names and IDs, in a different order or repeated"]
        );
    }

    #[test]
    fn unreadable_header_line_fails() {
        assert_eq!(
            header_string_ids("static const StringID STR_A = 12;\n"),
            Err("unreadable string ID line: static const StringID STR_A = 12;".to_owned())
        );
    }
}
