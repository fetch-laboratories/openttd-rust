pub fn layout(name: &str, item: usize) -> usize {
    let local = local_layout(name, item);
    if local != usize::MAX {
        return local;
    }
    for layout in [
        crate::company::abi_layout,
        crate::crypto_primitives::abi_layout,
        crate::blake2b::abi_layout,
        crate::x25519::abi_layout,
        crate::auth::abi_layout,
    ] {
        let value = layout(name, item);
        if value != usize::MAX {
            return value;
        }
    }
    usize::MAX
}
