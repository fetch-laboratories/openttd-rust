/** @file station_command_services.hpp Native leaves for station construction. */
#ifndef RUST_STATION_COMMAND_SERVICES_HPP
#define RUST_STATION_COMMAND_SERVICES_HPP
#include "services_map.h"
#include "services_industry.h"
#include "services_rail.h"
#include "company_services.h"
#include "waypoint_layout.h"

const OpenTTDStationCommandServices &GetRustStationCommandServices() noexcept
{
	static const OpenTTDStationCommandServices services{
		.shared = &GetRustSharedServices(),
		.station = &GetRustStationServices(),
		.rail = &GetRustRailCommandServices(),
		.cost = &GetRustCommandCostServices(),
		.command = &GetRustCommandServices(),
		.authority = &GetRustTownAuthorityServices(),
		.spread = RustStationSpread,
		.default_bridge_info = [](uint8_t type) noexcept -> OpenTTDStationBridgeInfo { auto info = GetStationBridgeableTileInfo(static_cast<StationType>(type)); return {info.data(), info.size()}; },
		.rail_bridge_info = [](const StationSpec *spec) noexcept -> OpenTTDStationBridgeInfo { return {spec->bridgeable_info.data(), RustStationBridgeInfoCount(spec)}; },
		.road_bridge_info = [](const RoadStopSpec *spec) noexcept -> OpenTTDStationBridgeInfo { return {spec->bridgeable_info.data(), RustStationBridgeInfoCount(spec)}; },
		.southern_bridge_end = [](uint32_t tile) noexcept { return GetSouthernBridgeEnd(TileIndex{tile}).base(); },
		.tile_area = [](const BaseStation *st, uint8_t type) noexcept -> OpenTTDStationArea { const auto area = st->GetTileArea(static_cast<StationType>(type)); return {area.tile.base(), area.w, area.h}; },
		.rail_spec = RustAnimationRailSpec,
		.links = &_rust_station_links,
		.base_move_sign = [](BaseStation *st, uint32_t tile) noexcept { st->BaseStation::MoveSign(TileIndex{tile}); },
		.waypoint_move_sign = [](BaseStation *st, uint32_t tile) noexcept { Waypoint::From(st)->MoveSign(TileIndex{tile}); },
		.virtual_coord = [](BaseStation *st) noexcept { st->UpdateVirtCoord(); },
		.catchment_dirty = []() noexcept { MarkCatchmentTilesDirty(); },
		.facility_widget = [](BaseStation *st, uint8_t type) noexcept {
			switch (static_cast<StationType>(type)) {
				case StationType::Rail: SetWindowWidgetDirty(WC_STATION_VIEW, st->index, WID_SV_TRAINS); break;
				case StationType::Airport: break;
				case StationType::Bus: case StationType::Truck: SetWindowWidgetDirty(WC_STATION_VIEW, st->index, WID_SV_ROADVEHS); break;
				case StationType::Dock: SetWindowWidgetDirty(WC_STATION_VIEW, st->index, WID_SV_SHIPS); break;
				default: NOT_REACHED();
			}
		},
		.station_available = RustStationStationAvailable,
		.new_station = [](uint32_t tile) noexcept -> BaseStation * { return new Station(TileIndex{tile}); },
		.set_town = RustStationSetTown,
		.lifecycle = &GetRustStationLifecycleServices(),
		.have_rating = RustStationHaveRating,
		.road_waypoint = RustStationRoadWaypoint,
		.name_equals = [](BaseStation *st, const uint8_t *text, size_t length) noexcept { return !st->name.empty() && st->name == std::string_view(reinterpret_cast<const char *>(text), length); },
		.set_name = RustStationSetName,
		.flip_airport_closed = [](BaseStation *st) noexcept { Station::From(st)->airport.blocks.Flip(AirportBlock::AirportClosed); },
		.distant_join = RustStationDistantJoin,
		.rail_association = &GetStationAssociationServices(),
		.rail_spec_info = [](const StationSpec *spec) noexcept -> OpenTTDRailStationSpecInfo { return {spec->disallowed_platforms, spec->disallowed_lengths, spec->callback_mask.Test(StationCallbackMask::SlopeCheck), spec->callback_mask.Test(StationCallbackMask::Avail)}; },
		.rail_layout = [](const StationSpec *spec, uint16_t key) noexcept -> OpenTTDByteSpan { if (spec == nullptr) return {nullptr, 0}; auto it = spec->layouts.find(key); if (it == spec->layouts.end()) return {nullptr, 0}; return {it->second.data(), it->second.size()}; },
		.rail_boolean = RustStationConvert8bitBoolean,
		.rail_callback_error = RustSpecCallbackError<StationSpec, StationSpec>,
		.set_train_area = [](BaseStation *st, OpenTTDStationArea area) noexcept { st->train_station = TileArea(TileIndex{area.tile}, area.w, area.h); },
		.last_train = RustVehicleLast<Train>,
		.train = &GetTrainServices(),

		.custom_rail_index = RustCustomStationIndex,
		.make_rail_station = [](uint32_t tile, uint8_t owner, uint16_t id, uint8_t axis, uint8_t gfx, uint8_t rt) noexcept { MakeRailStation(TileIndex{tile}, Owner(owner), StationID(id), static_cast<Axis>(axis), gfx, static_cast<RailType>(rt)); },
		.close_station_inspect = RustStationCloseInspect,
		.set_custom_rail_index = [](uint32_t tile, uint8_t index) noexcept { SetCustomStationSpecIndex(TileIndex{tile}, index); },
		.set_random_bits = [](uint32_t tile, uint8_t bits) noexcept { SetStationTileRandomBits(TileIndex{tile}, bits); },
		.set_gfx = [](uint32_t tile, uint8_t gfx) noexcept { SetStationGfx(TileIndex{tile}, gfx); },
		.tile_flag_count = RustStationTileFlagCount,
		.tile_flags = [](const StationSpec *spec, uint8_t gfx) noexcept { return spec->tileflags[gfx].base(); },
		.set_tile_flags = [](uint32_t tile, bool blocked, bool pylons, bool wires) noexcept { SetStationTileBlocked(TileIndex{tile}, blocked); SetStationTileHavePylons(TileIndex{tile}, pylons); SetStationTileHaveWires(TileIndex{tile}, wires); },
		.reset_facilities = RustStationResetFacilities,
		.orders_dirty = []() noexcept { SetWindowClassesDirty(WC_VEHICLE_ORDERS); },
		.vehicle = &GetRustVehicleServices(),
				.stop_on_town_road = RustStationStopOnTownRoad,
		.stop_on_competitor_road = RustStationStopOnCompetitorRoad,
		.road_spec_info = [](const RoadStopSpec *spec) noexcept -> OpenTTDRoadStationSpecInfo { return {spec->stop_type, spec->flags.Test(RoadStopSpecFlag::DriveThroughOnly), spec->callback_mask.Test(RoadStopCallbackMask::Avail)}; },
		.road_spec_build_cost = [](const RoadStopSpec *spec, uint8_t price) noexcept -> OpenTTDRoadStationSpecCost { return {spec->build_cost_multiplier, RustGRFPriceShift(RustSpecGRFFile(spec), price)}; },
		.road_spec_clear_cost = [](const RoadStopSpec *spec, uint8_t price) noexcept -> OpenTTDRoadStationSpecCost { return {spec->clear_cost_multiplier, RustGRFPriceShift(RustSpecGRFFile(spec), price)}; },
		.stops_available = [](size_t count) noexcept { return RoadStop::CanAllocateItem(count); },
		.roadstop_resolver = &GetRoadStopResolverServices(),
		.road_boolean = RustRoadStopConvert8bitBoolean,
		.road_triggers = RustStationRoadTriggers,
		.new_stop = [](uint32_t tile) noexcept { return new RoadStop(TileIndex{tile}); },
		.set_stop_head = [](BaseStation *st, bool truck, RoadStop *head) noexcept { (truck ? Station::From(st)->truck_stops : Station::From(st)->bus_stops) = head; },
		.set_stop_next = [](RoadStop *stop, RoadStop *next) noexcept { stop->next = next; },
		.stop_area = RustStationStopArea,
		.clear_stop_area = [](BaseStation *st, bool truck) noexcept { (truck ? Station::From(st)->truck_station : Station::From(st)->bus_station).Clear(); },
		.make_drive_stop = [](uint32_t tile, uint8_t owner, uint8_t road, uint8_t tram, uint16_t id, uint8_t type, uint8_t road_rt, uint8_t tram_rt, uint8_t axis) noexcept { MakeDriveThroughRoadStop(TileIndex{tile}, Owner(owner), Owner(road), Owner(tram), StationID(id), static_cast<StationType>(type), static_cast<RoadType>(road_rt), static_cast<RoadType>(tram_rt), static_cast<Axis>(axis)); },
		.make_bay_stop = [](uint32_t tile, uint8_t owner, uint16_t id, uint8_t type, uint8_t road_rt, uint8_t tram_rt, uint8_t dir) noexcept { MakeRoadStop(TileIndex{tile}, Owner(owner), StationID(id), static_cast<RoadStopType>(type), static_cast<RoadType>(road_rt), static_cast<RoadType>(tram_rt), static_cast<DiagDirection>(dir)); },
		.delete_stop = [](RoadStop *stop) noexcept { delete stop; },
		.set_custom_road_index = [](uint32_t tile, uint8_t index) noexcept { SetCustomRoadStopSpecIndex(TileIndex{tile}, index); },
		.custom_road_index = RustCustomRoadStopIndex,
		.remove_stop_tile_data = [](BaseStation *st, uint32_t tile) noexcept { st->RemoveRoadStopTileData(TileIndex{tile}); },
		.close_stop_inspect = RustRoadStopCloseInspect,
		.set_road_waypoint_area = [](BaseStation *st, OpenTTDStationArea area) noexcept { Waypoint::From(st)->road_waypoint_area = TileArea(TileIndex{area.tile}, area.w, area.h); },
		.road_vehicle_owner = [](OpenTTDVehicle *v) noexcept { return RoadStateOf(RoadVehicle::From(VehicleOf(v))); },
		.order_station_location = RustVehicleOrderStationLocation,
		.aircraft = &GetRustAircraftLeaves(),
		.airport_runtime = &GetAirportResolverServices(),
		.airport_layout_count = [](const AirportSpec *spec) noexcept { return spec->layouts.size(); },
		.airport_size = [](const AirportSpec *spec) noexcept -> OpenTTDAirportSize { return {spec->size_x, spec->size_y}; },
		.airport_layout = [](const AirportSpec *spec, uint8_t layout) noexcept -> OpenTTDAirportLayout { return {spec->layouts[layout].tiles.size(), spec->layouts[layout].rotation}; },
		.airport_layout_tile = [](const AirportSpec *spec, uint8_t layout, uint32_t origin, size_t index) noexcept -> OpenTTDAirportLayoutTile { const auto &t = spec->layouts[layout].tiles[index]; return {(TileIndex{origin} + ToTileIndexDiff(t.ti)).base(), t.gfx}; },
		.iterator_tile = [](TileIterator *it) noexcept { return (**it).base(); },
		.iterator_next = [](TileIterator *it) noexcept { ++(*it); },
		.airport_noise = [](const AirportSpec *spec) noexcept { return spec->noise_level; },
		.town_max_noise = [](const OpenTTDTownHandle *town) noexcept { return reinterpret_cast<const Town *>(town)->MaxTownNoise(); },
		.station_town = RustStationStationTown,
		.airport_tile = RustStationAirportTile,
		.airport_type = RustStationAirportType,
		.airport_rotation = RustStationAirportRotation,
		.airport_airplanes = [](const AirportFTAClass *fta) noexcept { return fta->flags.Test(AirportFTAClass::Flag::Airplanes); },
		.set_airport_details = [](BaseStation *base, uint8_t type, uint8_t layout, uint8_t rotation) noexcept { auto &a = Station::From(base)->airport; a.type = type; a.layout = layout; a.blocks = {}; a.rotation = static_cast<Direction>(rotation); },
		.make_airport = [](uint32_t tile, uint8_t owner, uint16_t id, uint8_t gfx, uint8_t water) noexcept { MakeAirport(Tile{TileIndex{tile}}, Owner(owner), StationID(id), gfx, static_cast<WaterClass>(water)); },
		.airport_area = RustStationAirportArea,
		.airport_animated = [](const AirportTileSpec *spec) noexcept { return spec->animation.status != AnimationStatus::NoAnimation; },
		.station_view_invalidate = RustStationStationViewInvalidate,
		.town_view_dirty = [](const OpenTTDTownHandle *town) noexcept { SetWindowDirty(WC_TOWN_VIEW, reinterpret_cast<const Town *>(town)->index); },
		.aircraft_vehicle = GetRustAircraftVehicle,
		.hangar_count = [](BaseStation *st, const AirportSpec *spec) noexcept { return Station::From(st)->airport.GetNumHangars(spec); },
		.hangar_tile = RustSelectedHangarTile,
		.delete_airport_storage = RustStationDeleteAirportStorage,
		.clear_airport = RustStationClearAirport,
		.clear = &GetRustClearServices(),
		.restoration = &GetRustWaterRestorationServices(),

		.set_docking = OpenTTDSetDockingTile,
		.set_ship_area = [](BaseStation *st, OpenTTDStationArea area) noexcept { Station::From(st)->ship_station = TileArea(TileIndex{area.tile}, area.w, area.h); },
		.ship_station_area = RustStationShipArea,
		.docking_clear = [](BaseStation *st) noexcept { Station::From(st)->docking_station.Clear(); },
		.docking_area = RustStationDockingArea,
		.make_dock = [](uint32_t tile, uint8_t owner, uint16_t id, uint8_t dir, uint8_t water) noexcept { MakeDock(TileIndex{tile}, Owner(owner), StationID(id), static_cast<DiagDirection>(dir), static_cast<WaterClass>(water)); },
		.neutral_for_tile = [](uint32_t tile) noexcept -> BaseStation * { return RustIndustryNeutralStation(RustIndustryByTile(tile)); },
		.associate_industry = [](BaseStation *st, uint32_t tile) noexcept { auto *s = Station::From(st); s->industry = RustIndustryByTile(tile); s->industry->neutral_station = s; },
		.make_oilrig = [](uint32_t tile, uint16_t id, uint8_t water) noexcept { MakeOilrig(TileIndex{tile}, StationID(id), static_cast<WaterClass>(water)); },
		.set_station_owner = RustStationSetStationOwner,
		.set_airport_kind_rotation = [](BaseStation *st, uint8_t type, uint8_t rotation) noexcept { auto &a = Station::From(st)->airport; a.type = type; a.rotation = static_cast<Direction>(rotation); },
		.set_facilities = RustStationSetFacilities,
		.set_build_date = RustStationSetBuildDate,
		.associated_industry = RustStationAssociatedIndustry,
		.industry_neutral = RustIndustryNeutralBaseStation,
		.clear_industry_neutral = [](Industry *industry) noexcept { industry->neutral_station = nullptr; },
		.industry_area = [](Industry *industry) noexcept -> OpenTTDStationArea { const auto &a = industry->location; return {a.tile.base(), a.w, a.h}; },
		.autoslope_axis = [](uint32_t tile, int32_t z, uint8_t slope, uint8_t axis) noexcept { return AutoslopeCheckForAxis(TileIndex{tile}, z, static_cast<Slope>(slope), static_cast<Axis>(axis)); },
			.station_list_classes_invalidate = RustStationListClassesInvalidate,
		.clear_cached_name = RustStationClearCachedName,
		.clear_name = RustStationClearName,
		.make_buoy = RustMakeBuoy,
		.make_rail_waypoint = RustMakeRailWaypoint,
		.new_waypoint = [](uint32_t tile) noexcept -> BaseStation * { return new Waypoint(TileIndex{tile}); },
		.road_ground = &GetRustRoadGroundServices(),
		.road_waypoint_tile_area = RustWaypointRoadArea,
		.set_facility_bits = RustStationSetFacilityBits,
		.set_location = RustStationSetLocation,
		.set_rail_station_reservation = RustSetRailStationReservation,
		.set_road_waypoint = RustWaypointSetRoad,
		.set_string_id = RustStationSetStringID,
		.string_id = RustStationStringID,
		.tile_flat = OpenTTDIsTileFlat,
		.waypoint_available = RustWaypointAvailable,
		.waypoint_default_name = RustWaypointDefaultName,
		.waypoint_layout_gfx = [](OpenTTDWaypointLayout *frame, bool first) noexcept { if (first) frame->iterator.emplace(frame->layout->begin()); return *(*frame->iterator)++; },
		.waypoint_layout_init = [](OpenTTDWaypointLayout *frame, const StationSpec *spec, uint8_t count) noexcept { frame->layout.emplace(spec, count, 1); },
		.waypoint_view_invalidate = RustWaypointViewInvalidate,
	};
	return services;
}
#endif /* RUST_STATION_COMMAND_SERVICES_HPP */
